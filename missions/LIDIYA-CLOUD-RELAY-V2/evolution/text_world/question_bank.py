CONTEXTS = [
    "你只有30秒", "你不能查網路", "這個決定可回滾", "這個決定不可回滾",
    "另一位模型反對你", "過去記憶支持相反答案", "使用者沒有給偏好",
    "資料來源可能被污染", "你必須留下可驗證證據", "結果會延遲一年才知道",
]


def generate_questions(count: int = 100, seed: int = 42):
    """Return 1..1000 deterministic open-ended questions.

    The first 100 are hand-authored seeds. 101..1000 are controlled context variants,
    not arbitrary paraphrases, so holdout families remain inspectable.
    """
    if not 1 <= count <= 1000:
        raise ValueError("count must be in 1..1000")
    base = []
    for category, stems in STEMS.items():
        for idx, question in enumerate(stems, 1):
            base.append({
                "id": f"{category.upper()}-{idx:03d}",
                "category": category,
                "question": question,
                "targets": TARGETS[category],
                "synthetic": False,
            })
    if count <= len(base):
        return base[:count]

    rng = random.Random(seed)
    out = list(base)
    variant = 1
    while len(out) < count:
        shuffled = list(base)
        rng.shuffle(shuffled)
        context = CONTEXTS[(variant - 1) % len(CONTEXTS)]
        for item in shuffled:
            if len(out) >= count:
                break
            out.append({
                "id": f"{item['id']}-V{variant}",
                "category": item["category"],
                "question": f"情境：{context}。{item['question']}",
                "targets": item["targets"],
                "synthetic": True,
                "parent_id": item["id"],
                "variant_context": context,
            })
        variant += 1
    return out
